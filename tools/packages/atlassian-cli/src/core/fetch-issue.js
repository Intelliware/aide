const fs = require('fs');
const path = require('path');
const JiraClient = require('../api/jira-client');
const { getWorkspaceRoot } = require('../utils/env-loader');

/**
 * Load project-specific field mapping
 * @param {string} projectKey - Project key extracted from issue (e.g., DIGSTART, CEAJ)
 * @returns {Object} Field mapping object { customfield_XXXXX: "Field Name", ... }
 */
function loadFieldMapping(projectKey) {
  const mappingsBasePath = path.join(__dirname, '..', 'field-mappings');
  const projectMappingPath = path.join(mappingsBasePath, projectKey, 'fields.json');
  
  if (fs.existsSync(projectMappingPath)) {
    try {
      return JSON.parse(fs.readFileSync(projectMappingPath, 'utf8'));
    } catch (error) {
      console.warn(`⚠️  Failed to load field mapping for ${projectKey}: ${error.message}`);
      return {};
    }
  }
  
  // No mapping exists - will be auto-generated during fetch
  return {};
}

/**
 * Generate field mapping for a project from an issue
 * @param {string} issueKey - Issue key (e.g., DIGSTART-1258)
 * @param {Object} issue - Full issue object from Jira API
 * @returns {boolean} True if mapping was generated successfully
 */
function generateFieldMappingForProject(issueKey, issue) {
  const projectKey = issueKey.split('-')[0];
  const mappingsBasePath = path.join(__dirname, '..', 'field-mappings');
  const projectMappingDir = path.join(mappingsBasePath, projectKey);
  const projectMappingPath = path.join(projectMappingDir, 'fields.json');
  
  // Skip if mapping already exists
  if (fs.existsSync(projectMappingPath)) {
    return false;
  }
  
  console.log(`\n📋 Generating field mapping for project: ${projectKey}`);
  
  // Create project directory
  fs.mkdirSync(projectMappingDir, { recursive: true });
  
  // Extract custom fields from issue
  const fields = issue.fields || {};
  const fieldMapping = {};
  
  Object.keys(fields).forEach(fieldId => {
    if (fieldId.startsWith('customfield_')) {
      const value = fields[fieldId];
      
      // Try to determine field name from value structure
      let fieldName = fieldId;
      if (value && typeof value === 'object') {
        if (value.name) fieldName = value.name;
        else if (value.value) fieldName = value.value;
      }
      
      fieldMapping[fieldId] = fieldName;
    }
  });
  
  // Save mapping
  fs.writeFileSync(projectMappingPath, JSON.stringify(fieldMapping, null, 2));
  
  const fieldCount = Object.keys(fieldMapping).length;
  console.log(`✓ Generated mapping with ${fieldCount} custom fields`);
  console.log(`✓ Saved to: ${projectMappingPath}\n`);
  
  return true;
}

/**
 * Remove the legacy markdown artifact from older CLI runs.
 * Markdown analysis is now generated by the agent from cached JSON.
 * @param {string} markdownPath - Legacy markdown file path
 * @param {boolean} silent - Suppress console output
 */
function removeLegacyMarkdown(markdownPath, silent = false) {
  if (!fs.existsSync(markdownPath)) {
    return;
  }

  fs.unlinkSync(markdownPath);

  if (!silent) {
    console.log(`ℹ Removed legacy Markdown artifact: ${markdownPath}`);
  }
}

/**
 * Fetch a Jira issue and save it locally
 * @param {string} issueKey - Jira issue key (e.g., PROJ-123)
 * @param {object} options - Options object
 * @param {boolean} options.useCache - Whether to use cached version if available (default: true)
 * @param {string} options.outputDir - Base output directory (overrides OUTPUT_DIR env var)
 * @param {boolean} options.silent - Suppress console output (default: false)
 * @returns {Promise<object>} Result object with success status and paths
 */
async function fetchIssue(issueKey, options = {}) {
  const projectKey = issueKey.split('-')[0];
  
  // Get base output directory from env or use workspace root default
  const workspaceRoot = getWorkspaceRoot();
  const defaultOutputDir = process.env.OUTPUT_DIR 
    ? (path.isAbsolute(process.env.OUTPUT_DIR) 
        ? process.env.OUTPUT_DIR 
        : path.join(workspaceRoot, process.env.OUTPUT_DIR))
    : path.join(workspaceRoot, 'docs');
  
  const {
    useCache = true,
    outputDir: baseDir = path.join(defaultOutputDir, 'jira', projectKey),
    silent = false
  } = options;
  
  const outputDir = path.join(baseDir, issueKey);
  const jsonPath = path.join(outputDir, `${issueKey}.json`);
  const metaPath = path.join(outputDir, '.meta.json');
  const analysisPath = path.join(outputDir, `${issueKey}.analysis.md`);
  const legacyMarkdownPath = path.join(outputDir, `${issueKey}.md`);
  
  // Check if cached version exists
  if (fs.existsSync(metaPath) && useCache) {
    const meta = JSON.parse(fs.readFileSync(metaPath, 'utf8'));
    const lastFetch = new Date(meta.lastFetch);
    const now = new Date();
    const diffMinutes = Math.floor((now - lastFetch) / 1000 / 60);
    const diffHours = Math.floor(diffMinutes / 60);
    const diffDays = Math.floor(diffHours / 24);
    
    let timeAgo;
    if (diffMinutes < 60) {
      timeAgo = `${diffMinutes} minute${diffMinutes !== 1 ? 's' : ''} ago`;
    } else if (diffHours < 24) {
      timeAgo = `${diffHours} hour${diffHours !== 1 ? 's' : ''} ago`;
    } else {
      timeAgo = `${diffDays} day${diffDays !== 1 ? 's' : ''} ago`;
    }
    
    if (!silent) {
      console.log(`\n📦 Cached version found (fetched ${timeAgo})`);
      console.log(`   Checking if remote has updates...`);
    }
    
    // Check if remote has been modified (lightweight timestamp check)
    try {
      const jiraUrl = process.env.JIRA_URL || process.env.ATLASSIAN_URL || 'https://your-jira.atlassian.net';
      const client = new JiraClient({ baseURL: jiraUrl });
      const { updated: remoteUpdated } = await client.getIssueTimestamp(issueKey);
      
      const cachedUpdated = meta.updated;
      const isUpToDate = cachedUpdated === remoteUpdated;
      
      if (!silent) {
        console.log(`   Cached timestamp:  ${cachedUpdated || 'unknown'}`);
        console.log(`   Remote timestamp:  ${remoteUpdated}`);
        
        if (isUpToDate) {
          console.log(`   ✓ Cache is up to date!`);
          console.log(`\n📄 Using cached version. Use --fresh flag to force re-fetch.\n`);
        } else {
          console.log(`   ⚠ Remote has been updated - fetching fresh copy...\n`);
        }
      }
      
      if (isUpToDate) {
        removeLegacyMarkdown(legacyMarkdownPath, silent);

        return {
          success: true,
          cached: true,
          cacheUpToDate: true,
          timeAgo,
          paths: { outputDir, jsonPath, metaPath, analysisPath },
          meta
        };
      }
      
      // Fall through to fetch fresh copy
      if (!silent) {
        console.log(`🔄 Fetching updated version from Jira...`);
      }
      
    } catch (timestampError) {
      // If timestamp check fails, use cached version anyway
      if (!silent) {
        console.log(`   ⚠ Could not check remote timestamp: ${timestampError.message}`);
        console.log(`   📄 Using cached version.\n`);
      }
      
      return {
        success: true,
        cached: true,
        cacheUpToDate: null,
        timeAgo,
        paths: { outputDir, jsonPath, metaPath, analysisPath },
        meta
      };
    }
  }
  
  if (!silent && !fs.existsSync(metaPath)) {
    console.log(`\n🔄 Fetching Jira issue: ${issueKey}...`);
  }
  
  // Override baseURL for Jira if JIRA_URL is set
  const { getJiraUrl } = require('../utils/defaults');
  const jiraUrl = getJiraUrl();
  const client = new JiraClient({ baseURL: jiraUrl });
  
  try {
    // Fetch the issue with all fields
    const issue = await client.getIssue(issueKey);
    
    if (!silent) {
      console.log(`✓ Retrieved issue: ${issue.key} - ${issue.fields.summary}`);
    }
    
    // Auto-generate field mapping if it doesn't exist for this project
    const projectKey = issueKey.split('-')[0];
    const mappingGenerated = generateFieldMappingForProject(issueKey, issue);
    
    if (mappingGenerated && !silent) {
      console.log(`💡 Tip: You can customize the field mapping at:`);
      console.log(`   src/field-mappings/${projectKey}/fields.json\n`);
    }
    
    // Create output directory
    fs.mkdirSync(outputDir, { recursive: true });
    
    // Save metadata with timestamp
    const metadata = {
      issueKey: issue.key,
      lastFetch: new Date().toISOString(),
      summary: issue.fields.summary,
      status: issue.fields.status?.name,
      updated: issue.fields.updated,
      analysisFile: path.basename(analysisPath)
    };
    fs.writeFileSync(metaPath, JSON.stringify(metadata, null, 2));
    
    // Save raw JSON
    fs.writeFileSync(jsonPath, JSON.stringify(issue, null, 2));
    
    if (!silent) {
      console.log(`✓ Saved JSON: ${jsonPath}`);
    }

    removeLegacyMarkdown(legacyMarkdownPath, silent);
    
    if (!silent) {
      console.log(`ℹ Markdown analysis is agent-generated from cached JSON: ${analysisPath}`);
      console.log(`\n✅ Done! Files saved to: ${outputDir}\n`);
    }
    
    return {
      success: true,
      cached: false,
      cacheUpToDate: false,
      issue,
      paths: { outputDir, jsonPath, metaPath, analysisPath },
      meta: metadata
    };
  } catch (error) {
    if (!silent) {
      console.error(`\n✗ Error fetching issue:`, error.message);
      if (error.response) {
        console.error(`  Status: ${error.response.status}`);
        console.error(`  Response:`, error.response.data);
      }
    }
    
    return {
      success: false,
      error: error.message,
      errorResponse: error.response
    };
  }
}

function convertIssueToMarkdown(issue, jiraUrl = 'https://your-jira.atlassian.net') {
  const fields = issue.fields;
  
  // Extract project key from issue key (e.g., DIGSTART-1258 → DIGSTART)
  const projectKey = issue.key.split('-')[0];
  
  // Load project-specific field mapping
  const fieldMapping = loadFieldMapping(projectKey);
  
  // YAML Frontmatter with metadata
  let md = '---\n';
  md += `issue_key: ${issue.key}\n`;
  md += `issue_type: ${fields.issuetype?.name || 'N/A'}\n`;
  md += `status: ${fields.status?.name || 'N/A'}\n`;
  md += `priority: ${fields.priority?.name || 'N/A'}\n`;
  
  // Custom field metadata (using field mapping)
  const metadataFields = [
    { id: 'customfield_27100', name: 'feature_type' },
    { id: 'customfield_26904', name: 'feature_size' },
    { id: 'customfield_27400', name: 'change_category' },
    { id: 'customfield_29600', name: 'feature_category' },
    { id: 'customfield_32700', name: 'qbr' },
    { id: 'customfield_27006', name: 'work_type' },
    { id: 'customfield_28100', name: 'capitalized' },
    { id: 'customfield_29400', name: 'transitioning_project' },
    { id: 'customfield_13355', name: 'clarity_id' },
    { id: 'customfield_26903', name: 'feature_owner' },
    { id: 'customfield_27201', name: 'residual_risk_rating' },
    { id: 'customfield_27301', name: 'target_end' },
  ];
  
  metadataFields.forEach(({ id, name }) => {
    const value = fields[id];
    if (value) {
      let yamlValue = '';
      if (typeof value === 'string') {
        yamlValue = value.includes(':') ? `"${value}"` : value;
      } else if (value.displayName) {
        yamlValue = value.displayName;
      } else if (value.name) {
        yamlValue = value.name;
      } else if (value.value) {
        yamlValue = value.value;
      }
      if (yamlValue) {
        md += `${name}: ${yamlValue}\n`;
      }
    }
  });
  
  md += `created: ${fields.created || 'N/A'}\n`;
  md += `updated: ${fields.updated || 'N/A'}\n`;
  
  if (fields.labels && fields.labels.length > 0) {
    md += `labels:\n`;
    fields.labels.forEach(label => {
      md += `  - ${label}\n`;
    });
  }
  
  if (fields.components && fields.components.length > 0) {
    md += `components:\n`;
    fields.components.forEach(comp => {
      md += `  - ${comp.name}\n`;
    });
  }
  
  md += '---\n\n';
  
  // Title
  md += `# ${issue.key}: ${fields.summary}\n\n`;
  
  // Reporter and Assignee
  md += `**Reporter:** ${fields.reporter?.displayName || 'N/A'}  \n`;
  md += `**Assignee:** ${fields.assignee?.displayName || 'Unassigned'}  \n\n`;
  
  md += `---\n\n`;
  
  // Table of Contents
  md += `## Table of Contents\n\n`;
  if (fields.customfield_26905) md += `- [Feature Statement](#feature-statement)\n`;
  if (fields.customfield_14400) md += `- [Acceptance Criteria](#acceptance-criteria)\n`;
  if (fields.description) md += `- [Description](#description)\n`;
  if (fields.comment && fields.comment.comments && fields.comment.comments.length > 0) {
    md += `- [Comments](#comments)\n`;
  }
  if (fields.subtasks && fields.subtasks.length > 0) md += `- [Subtasks](#subtasks)\n`;
  md += `- [Links](#links)\n`;
  md += `\n---\n\n`;
  
  // Feature Statement (customfield_26905) - First priority section
  if (fields.customfield_26905) {
    md += `## Feature Statement\n\n`;
    md += convertJiraMarkupToMarkdown(fields.customfield_26905);
    md += `\n\n`;
  }
  
  // Acceptance Criteria (customfield_14400) - Second priority section
  if (fields.customfield_14400) {
    md += `## Acceptance Criteria\n\n`;
    md += convertJiraMarkupToMarkdown(fields.customfield_14400);
    md += `\n\n`;
  }
  
  // Description with panel support - Third section
  if (fields.description) {
    md += `## Description\n\n`;
    md += convertJiraMarkupToMarkdown(fields.description);
    md += `\n\n`;
  }
  
  // Comments
  if (fields.comment && fields.comment.comments && fields.comment.comments.length > 0) {
    md += `## Comments\n\n`;
    fields.comment.comments.forEach((comment, index) => {
      md += `### Comment ${index + 1} by ${comment.author?.displayName || 'Unknown'}\n`;
      md += `_${new Date(comment.created).toLocaleString()}_\n\n`;
      md += convertJiraMarkupToMarkdown(comment.body);
      md += `\n\n`;
    });
  }
  
  // Subtasks
  if (fields.subtasks && fields.subtasks.length > 0) {
    md += `## Subtasks\n\n`;
    fields.subtasks.forEach(subtask => {
      md += `- [${subtask.fields.status.name}] ${subtask.key}: ${subtask.fields.summary}\n`;
    });
    md += `\n`;
  }
  
  // Links
  md += `## Links\n\n`;
  md += `- [View in Jira](${jiraUrl}/browse/${issue.key})\n`;
  
  return md;
}

function convertJiraMarkupToMarkdown(text) {
  if (!text) return '';
  
  // Simple conversion - this could be enhanced
  let md = text;
  
  // Headings
  md = md.replace(/^h1\.\s+(.*)$/gm, '# $1');
  md = md.replace(/^h2\.\s+(.*)$/gm, '## $1');
  md = md.replace(/^h3\.\s+(.*)$/gm, '### $1');
  md = md.replace(/^h4\.\s+(.*)$/gm, '#### $1');
  
  // Bold
  md = md.replace(/\*(\S.*?)\*/g, '**$1**');
  
  // Italic
  md = md.replace(/_(\S.*?)_/g, '_$1_');
  
  // Bullet lists
  md = md.replace(/^\*\s+/gm, '- ');
  
  // Numbered lists (keep as is)
  md = md.replace(/^#\s+/gm, '1. ');
  
  // Code blocks
  md = md.replace(/\{code\}/g, '```');
  md = md.replace(/\{code:([^}]+)\}/g, '```$1');
  
  // Inline code
  md = md.replace(/\{\{([^}]+)\}\}/g, '`$1`');
  
  // Links
  md = md.replace(/\[([^\|]+)\|([^\]]+)\]/g, '[$1]($2)');
  
  return md;
}

